"""Generate the UI's design tokens and fixed wording from their single sources (issue #42).

- design/tokens.json  ->  ui/src/generated/tokens.css  (CSS custom properties, both themes)
- src/refdesk/wording.py  ->  ui/src/generated/wording.ts  (status labels, stop banners)

Why: the UI must never hardcode a colour or paraphrase a status label (CLAUDE.md, PRD 8A).
Generating both files means a token or label changes in one place. A drift test
(tests/test_ui_codegen.py) fails CI when a committed file is stale. Regenerate with
`uv run python scripts/generate_ui.py`.

Dark mode follows the system unless the page forces a theme with `data-theme` on <html>.
"""

from __future__ import annotations

import json
import re
from collections.abc import Callable
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path
from types import ModuleType
from typing import Any

HEADER = "GENERATED by scripts/generate_ui.py from {source}. Do not edit; edit the source."


def load_tokens(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _channel(value: int) -> float:
    c = value / 255
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def relative_luminance(hex_colour: str) -> float:
    h = hex_colour.lstrip("#")
    r, g, b = (_channel(int(h[i : i + 2], 16)) for i in (0, 2, 4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast_ratio(a: str, b: str) -> float:
    """WCAG 2.x contrast ratio between two #RRGGBB colours, from 1 to 21."""
    high, low = sorted((relative_luminance(a), relative_luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def _theme_vars(tokens: dict[str, Any], theme: str, indent: str) -> list[str]:
    lines = [
        f"{indent}--color-{t['name']}: {t['value'][theme]};" for t in tokens["color"]["tokens"]
    ]
    lines += [f"{indent}--{t['name']}: {t['value'][theme]};" for t in tokens["shadow"]["tokens"]]
    return lines


def render_tokens_css(tokens: dict[str, Any]) -> str:
    out = [f"/* {HEADER.format(source='design/tokens.json')} */", "", ":root {"]
    out.append("  color-scheme: light dark;")
    out += _theme_vars(tokens, "light", "  ")
    for name, family in tokens["type"]["families"].items():
        out.append(f"  --font-{name}: {family};")
    for group in tokens["type"]["groups"]:
        for style in group["styles"]:
            prefix = f"  --type-{style['name']}"
            out.append(f"{prefix}-family: var(--font-{group['family']});")
            out.append(f"{prefix}-size: {style['fontSize']};")
            out.append(f"{prefix}-line: {style['lineHeight']};")
            out.append(f"{prefix}-weight: {style['fontWeight']};")
            if "letterSpacing" in style:
                out.append(f"{prefix}-tracking: {style['letterSpacing']};")
    for group in ("spacing", "radius"):
        out += [f"  --{t['name']}: {t['value']};" for t in tokens[group]["tokens"]]
    out += ["}", ""]
    # Dark: follow the system unless light is forced; or force it with data-theme="dark".
    out += ["@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {']
    out += _theme_vars(tokens, "dark", "    ")
    out += ["  }", "}", ""]
    out += [':root[data-theme="light"] {', "  color-scheme: light;", "}", ""]
    out += [':root[data-theme="dark"] {', "  color-scheme: dark;"]
    out += _theme_vars(tokens, "dark", "  ")
    out += ["}", ""]
    return "\n".join(out)


def _js(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def render_wording_ts(module: ModuleType) -> str:
    """Every StrEnum in the module becomes a const object plus a union type; an enum with a
    `banner` property also gets a code -> banner map; module-level string constants
    become exported constants."""
    out = [f"// {HEADER.format(source='src/refdesk/wording.py')}", ""]
    for name, value in vars(module).items():
        if isinstance(value, type) and issubclass(value, StrEnum) and value is not StrEnum:
            out.append(f"export const {name} = {{")
            out += [f"  {m.name}: {_js(m.value)}," for m in value]
            out += [
                "} as const;",
                f"export type {name} = (typeof {name})[keyof typeof {name}];",
                "",
            ]
            if isinstance(getattr(value, "banner", None), property):
                snake = re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()  # StopReason -> STOP_REASON
                out.append(f"export const {snake}_BANNER: Record<{name}, string> = {{")
                out += [f"  {m.value}: {_js(m.banner)}," for m in value]
                out += ["};", ""]
    for name, value in vars(module).items():
        if name.isupper() and isinstance(value, str):
            out += [f"export const {name} = {_js(value)};", ""]
    return "\n".join(out)


@dataclass(frozen=True)
class Output:
    path: str  # relative to the repo root
    render: Callable[[Path], str]


def _tokens(root: Path) -> str:
    return render_tokens_css(load_tokens(root / "design" / "tokens.json"))


def _wording(root: Path) -> str:
    from refdesk import wording

    return render_wording_ts(wording)


OUTPUTS = (
    Output("ui/src/generated/tokens.css", _tokens),
    Output("ui/src/generated/wording.ts", _wording),
)
